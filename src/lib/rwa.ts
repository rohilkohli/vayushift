import { GRAP_INFO, GRAP_DISCLAIMER } from "./grapRules";
import type { GrapStage } from "./types";

/** Cost of one 800 W radiant heater, INR. [assumption] */
export const HEATER_UNIT_COST_INR = 1600;

export interface HeaterPlan {
  totalCostInr: number;
  perFlatInr: number;
}

export function heaterPlan(flats: number, guards: number): HeaterPlan {
  const f = Math.min(500, Math.max(1, Math.round(flats) || 1));
  const g = Math.min(50, Math.max(0, Math.round(guards) || 0));
  const total = g * HEATER_UNIT_COST_INR;
  return { totalCostInr: total, perFlatInr: Math.ceil(total / f) };
}

export interface AdvisoryInput {
  stage: GrapStage;
  aqi: number;
  locationName: string;
  flats: number;
  guards: number;
}

const HI_STAGE: Record<GrapStage, string> = {
  NONE: "सामान्य",
  STAGE_1: "चरण I",
  STAGE_2: "चरण II",
  STAGE_3: "चरण III",
  STAGE_4: "चरण IV",
};

const HI_ACTIONS: Record<GrapStage, string[]> = {
  NONE: ["खिड़कियाँ सामान्य रूप से खोलें।"],
  STAGE_1: ["खिड़कियाँ केवल दोपहर में खोलें।", "झाड़ू की जगह गीला पोंछा लगाएँ।", "कचरा या लकड़ी न जलाएँ।"],
  STAGE_2: ["शयनकक्ष में एयर फ़िल्टर चलाएँ।", "काम दोपहर 3 से 4:30 के बीच करें।", "अकेले कार की जगह मेट्रो लें।"],
  STAGE_3: ["खिड़कियाँ बंद रखें, केवल दोपहर में 10 मिनट खोलें।", "बाहर जाना हो तो N95 मास्क पहनें।", "गार्ड के लिए अँगीठी की जगह बिजली का हीटर दें।"],
  STAGE_4: ["घर के अंदर रहें, फ़िल्टर तेज़ चलाएँ।", "ज़रूरी न हो तो बाहर न जाएँ।", "बुज़ुर्ग पड़ोसियों का हाल पूछें।"],
};

/** Deterministic bilingual WhatsApp advisory. Template-based on purpose: legal text must never be generated by an LLM. */
export function buildAdvisory(i: AdvisoryInput): { en: string; hi: string; combined: string } {
  const info = GRAP_INFO[i.stage];
  const plan = heaterPlan(i.flats, i.guards);
  const heaterEn =
    i.guards > 0
      ? `Night-guard heaters: ${i.guards} x Rs ${HEATER_UNIT_COST_INR} = Rs ${plan.totalCostInr} total (about Rs ${plan.perFlatInr} per flat).`
      : "";
  const heaterHi =
    i.guards > 0 ? `गार्ड हीटर: ${i.guards} x ₹${HEATER_UNIT_COST_INR} = कुल ₹${plan.totalCostInr} (लगभग ₹${plan.perFlatInr} प्रति फ़्लैट)।` : "";
  const en = [
    `*${i.locationName} Smog Advisory*`,
    `AQI ${i.aqi} | GRAP ${info.roman === "-" ? "not active" : `Stage ${info.roman} (${info.category})`}`,
    ...info.householdActions.map((a) => `- ${a}`),
    heaterEn,
    GRAP_DISCLAIMER,
  ]
    .filter(Boolean)
    .join("\n");
  const hi = [
    `*${i.locationName} स्मॉग सूचना*`,
    `AQI ${i.aqi} | GRAP ${HI_STAGE[i.stage]}`,
    ...HI_ACTIONS[i.stage].map((a) => `- ${a}`),
    heaterHi,
    "यह सामान्य जानकारी है। आधिकारिक नियम caqm.nic.in पर देखें।",
  ]
    .filter(Boolean)
    .join("\n");
  return { en, hi, combined: `${en}\n\n${hi}` };
}
